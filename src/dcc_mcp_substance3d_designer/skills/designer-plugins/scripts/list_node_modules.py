"""List the Designer node modules that back built-in plugins."""

from __future__ import annotations

from dcc_mcp_core.skill import skill_entry

from dcc_mcp_substance3d_designer.graph_modules import list_node_modules
from dcc_mcp_substance3d_designer.skill_support import typed_result


@skill_entry
def main(query: str = "", offset: int = 0, limit: int = 100, **_kwargs):
    return typed_result("Listed Designer node modules", list_node_modules, query, offset, limit)


if __name__ == "__main__":
    from dcc_mcp_core.skill import run_main

    run_main(main)
